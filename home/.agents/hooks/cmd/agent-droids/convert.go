package main

import (
	"fmt"
	"regexp"
	"slices"
	"strconv"
	"strings"
)

// generatedMarker opens the comment line every generated droid carries in its
// frontmatter. It is how a later run tells its own files from droids Droid
// installed or someone wrote by hand, which it must never overwrite or prune.
const generatedMarker = "# generated by dot from "

// agentFile is one Claude Code agent file: its flat frontmatter and its body.
type agentFile struct {
	fields map[string]string
	body   string
}

// result is what one agent converts to: a droid, or a reasoned skip.
type result interface{ agentName() string }

// droid is a rendered droid file, written to <name>.md.
type droid struct {
	name    string
	content string
}

// skipped is an agent Droid cannot run, with the reason printed in its place.
type skipped struct {
	name   string
	reason string
}

func (d droid) agentName() string   { return d.name }
func (s skipped) agentName() string { return s.name }

var keyPattern = regexp.MustCompile(`^[A-Za-z][A-Za-z0-9_-]*$`)

// parseAgent reads an agent file's frontmatter as flat `key: value` lines,
// which is every form the agents use. Anything richer -- a block scalar, a
// flow list, an indented continuation -- is an error rather than a guess, so a
// new form gets a conscious mapping instead of a silently wrong droid.
func parseAgent(raw string) (agentFile, error) {
	raw = strings.ReplaceAll(raw, "\r\n", "\n")
	rest, ok := strings.CutPrefix(raw, "---\n")
	if !ok {
		return agentFile{}, fmt.Errorf("does not start with a --- frontmatter line")
	}
	head, body, ok := strings.Cut(rest, "\n---\n")
	if !ok {
		return agentFile{}, fmt.Errorf("frontmatter has no closing --- line followed by a body")
	}

	fields := map[string]string{}
	for i, line := range strings.Split(head, "\n") {
		lineNo := i + 2
		if strings.TrimSpace(line) == "" || strings.HasPrefix(line, "#") {
			continue
		}
		key, value, ok := strings.Cut(line, ":")
		if !ok || !keyPattern.MatchString(key) {
			return agentFile{}, fmt.Errorf("frontmatter line %d (%q) is not a flat `key: value` line; "+
				"the generator reads no other YAML form", lineNo, line)
		}
		value = strings.TrimSpace(value)
		if value == "" || strings.ContainsAny(value[:1], "|>[{&*!") {
			return agentFile{}, fmt.Errorf("frontmatter line %d: %s uses a YAML form the generator does not "+
				"read (empty, block, flow, anchor or tag); write it as one `key: value` line", lineNo, key)
		}
		value, err := unquote(value)
		if err != nil {
			return agentFile{}, fmt.Errorf("frontmatter line %d: %s: %w", lineNo, key, err)
		}
		if _, dup := fields[key]; dup {
			return agentFile{}, fmt.Errorf("frontmatter line %d: %s is set twice", lineNo, key)
		}
		fields[key] = value
	}
	return agentFile{fields: fields, body: body}, nil
}

// unquote strips YAML double or single quotes from a scalar, leaving a plain
// one as it is.
func unquote(value string) (string, error) {
	switch value[0] {
	case '"':
		s, err := strconv.Unquote(value)
		if err != nil {
			return "", fmt.Errorf("malformed double-quoted value %s", value)
		}
		return s, nil
	case '\'':
		if len(value) < 2 || value[len(value)-1] != '\'' {
			return "", fmt.Errorf("unterminated single-quoted value %s", value)
		}
		return strings.ReplaceAll(value[1:len(value)-1], "''", "'"), nil
	}
	return value, nil
}

// droidTools maps a Claude Code tool to its Droid ID.
var droidTools = map[string]string{
	"Bash":      "Execute",
	"Write":     "Create",
	"WebFetch":  "FetchUrl",
	"Read":      "Read",
	"Edit":      "Edit",
	"Grep":      "Grep",
	"Glob":      "Glob",
	"LS":        "LS",
	"WebSearch": "WebSearch",
}

// droppedTools have nothing to list on the Droid side: Skill is always enabled
// for every droid, and NotebookEdit has no counterpart.
var droppedTools = map[string]bool{"Skill": true, "NotebookEdit": true}

// droidModels maps a Claude Code model alias to the BYOK model ID configured in
// .factory/settings.base.json (customModels), which a droid names as
// "custom:<model>".
var droidModels = map[string]string{
	"opus":    "custom:claude-opus-5-5",
	"sonnet":  "custom:claude-sonnet-5-5",
	"haiku":   "custom:claude-haiku-5-5",
	"fable":   "custom:claude-fable-5-1",
	"inherit": "inherit",
}

// droidEfforts maps a Claude Code effort level to Droid's reasoningEffort,
// which tops out at high.
var droidEfforts = map[string]string{
	"low":    "low",
	"medium": "medium",
	"high":   "high",
	"xhigh":  "high",
	"max":    "high",
}

// knownKeys are the frontmatter keys convert maps or deliberately drops. Any
// other key is an error, so a new field gets a decision instead of vanishing.
// color, maxTurns and skills have no Droid counterpart and are dropped.
var knownKeys = []string{
	"name", "description", "tools", "disallowedTools", "model", "effort",
	"color", "maxTurns", "skills",
}

// convert translates one agent into a droid, or a skip when Droid cannot run
// it. source is the agent's path, recorded in the generated marker.
func convert(a agentFile, source string) (result, error) {
	for key := range a.fields {
		if !slices.Contains(knownKeys, key) {
			return nil, fmt.Errorf("frontmatter key %q has no Droid mapping; add one to convert", key)
		}
	}
	name := a.fields["name"]
	if name == "" {
		return nil, fmt.Errorf("frontmatter has no name")
	}
	if strings.TrimSpace(a.body) == "" {
		return nil, fmt.Errorf("body is empty, and Droid rejects a droid with no system prompt")
	}

	allowed := splitList(a.fields["tools"])
	disallowed := splitList(a.fields["disallowedTools"])
	if slices.Contains(allowed, "Agent") {
		return skipped{name: name, reason: "lists the Agent tool, and Droid subagents cannot spawn subagents"}, nil
	}

	var lines []string
	add := func(key, value string) { lines = append(lines, key+": "+value) }
	add("name", name)
	if d := a.fields["description"]; d != "" {
		add("description", strconv.Quote(d))
	}
	if m := a.fields["model"]; m != "" {
		model, ok := droidModels[m]
		if !ok {
			return nil, fmt.Errorf("model %q has no Droid mapping; use one of opus, sonnet, haiku, fable, inherit", m)
		}
		add("model", model)
	}
	if e := a.fields["effort"]; e != "" {
		effort, ok := droidEfforts[e]
		if !ok {
			return nil, fmt.Errorf("effort %q is not a Claude Code effort level", e)
		}
		add("reasoningEffort", effort)
	}
	tools, err := toolsValue(allowed, disallowed)
	if err != nil {
		return nil, err
	}
	if tools != "" {
		add("tools", tools)
	}

	content := "---\n" + generatedMarker + source + "\n" + strings.Join(lines, "\n") + "\n---\n" + a.body
	return droid{name: name, content: content}, nil
}

// toolsValue renders the droid's tools field, or "" to allow every tool.
//
// An allowlist is translated tool by tool, less anything disallowed. With no
// allowlist, Claude Code allows everything but the disallowed tools, which
// Droid cannot express as a list; the closest it has is the read-only category,
// used when Edit and Write are both taken away.
//
// MCP tools are dropped: Droid rejects a tool ID it has no registered server
// for, and this setup configures no MCP servers for Droid.
func toolsValue(allowed, disallowed []string) (string, error) {
	if len(allowed) == 0 {
		if slices.Contains(disallowed, "Edit") && slices.Contains(disallowed, "Write") {
			return "read-only", nil
		}
		return "", nil
	}
	var ids []string
	for _, tool := range allowed {
		if slices.Contains(disallowed, tool) || droppedTools[tool] || strings.HasPrefix(tool, "mcp__") {
			continue
		}
		id, ok := droidTools[tool]
		if !ok {
			return "", fmt.Errorf("tool %q has no Droid mapping; add it to droidTools or droppedTools", tool)
		}
		if !slices.Contains(ids, id) {
			ids = append(ids, id)
		}
	}
	if len(ids) == 0 {
		return "", fmt.Errorf("no tools are left once unmapped ones are dropped, and an empty list would " +
			"not mean the same in Droid")
	}
	quoted := make([]string, len(ids))
	for i, id := range ids {
		quoted[i] = strconv.Quote(id)
	}
	return "[" + strings.Join(quoted, ", ") + "]", nil
}

// splitList splits a comma-separated frontmatter list, dropping empty items.
func splitList(s string) []string {
	var out []string
	for item := range strings.SplitSeq(s, ",") {
		if item = strings.TrimSpace(item); item != "" {
			out = append(out, item)
		}
	}
	return out
}

// isGenerated reports whether a droid file was written by this generator.
func isGenerated(content string) bool {
	_, rest, ok := strings.Cut(content, "\n")
	return strings.HasPrefix(content, "---\n") && ok && strings.HasPrefix(rest, generatedMarker)
}
